export default function HereneosScreen({ navigation }) {
  const [currentSectionIndex, setCurrentSectionIndex] = useState(0);

  const currentSection = hereneosData.sections[currentSectionIndex];

  const handleNext = () => {
    if (currentSectionIndex < hereneosData.sections.length - 1) {
      setCurrentSectionIndex(currentSectionIndex + 1);
    } else {
      navigation.navigate('AtifosScreen');
    }
  };

  const handlePrevious = () => {
    if (currentSectionIndex > 0) {
      setCurrentSectionIndex(currentSectionIndex - 1);
    } else {
      navigation.navigate('AmeHawaryatScreen');
    }
  };

  return (
    <SafeAreaView style={styles.container}>
      {/* ርዕስ (Header) */}
      <View style={styles.header}>
        <Text style={styles.headerTitle}>{hereneosData.title}</Text>
        <Text style={styles.chapterTitle}>{hereneosData.chapter} - {currentSection.sectionTitle}</Text>
      </View>

      {/* የንባብ ማሳያ (Content ScrollView) */}
      <ScrollView style={styles.contentContainer} showsVerticalScrollIndicator={false}>
        {currentSection.verses.map((verse, index) => (
          <Text key={index} style={styles.verseText}>{verse}</Text>
        ))}
      </ScrollView>

      {/* የዳስስ በተኖች (Next / Previous Buttons) */}
      <View style={styles.buttonContainer}>
        <TouchableOpacity 
          style={styles.button} 
          onPress={handlePrevious}
        >
          <Text style={styles.buttonText}>‹ ቀደመ (Prev)</Text>
        </TouchableOpacity>

        <TouchableOpacity 
          style={styles.button} 
          onPress={handleNext}
        >
          <Text style={styles.buttonText}>ቀጣይ (Next) ›</Text>
        </TouchableOpacity>
      </View>
    </SafeAreaView>
  );
}

