export default function HaymanoteAbewScreen({ navigation }) {
  const [currentChapterIndex, setCurrentChapterIndex] = useState(0);

  const chapter = almesmayaData.chapters[currentChapterIndex];

  const handleNext = () => {
    if (currentChapterIndex < almesmayaData.chapters.length - 1) {
      setCurrentChapterIndex(currentChapterIndex + 1);
    } else {
      // Yemechereshawu ምዕራፍ sidersa ወደ 'AmeHawaryatScreen' gezu yisadalu
      navigation.navigate('AmeHawaryatScreen');
    }
  };

  const handlePrevious = () => {
    if (currentChapterIndex > 0) {
      setCurrentChapterIndex(currentChapterIndex - 1);
    }
  };

  return (
    <SafeAreaView style={styles.container}>
      {/* Header */}
      <View style={styles.header}>
        <Text style={styles.headerTitle}>{almesmayaData.title}</Text>
        <Text style={styles.chapterTitle}>{chapter.title}</Text>
      </View>

      {/* Content ScrollView */}
      <ScrollView style={styles.contentContainer}>
        {chapter.verses.map((verse, index) => (
          <Text key={index} style={styles.verseText}>{verse}</Text>
        ))}
      </ScrollView>

      {/* Next / Previous Buttons */}
      <View style={styles.buttonContainer}>
        <TouchableOpacity 
          style={[styles.button, currentChapterIndex === 0 && styles.disabledButton]} 
          onPress={handlePrevious}
          disabled={currentChapterIndex === 0}
        >
          <Text style={styles.buttonText}>ቀደመ (Prev)</Text>
        </TouchableOpacity>

        <TouchableOpacity 
          style={styles.button} 
          onPress={handleNext}
        >
          <Text style={styles.buttonText}>
            {currentChapterIndex === almesmayaData.chapters.length - 1 ? 'ወደ አመ ሐዋርያት ›' : 'ቀጣይ (Next)'}
          </Text>
        </TouchableOpacity>
      </View>
    </SafeAreaView>
  );
}

